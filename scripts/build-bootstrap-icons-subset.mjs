#!/usr/bin/env node
/**
 * OBRS-392. Regenerates the Bootstrap Icons subset held in `src/styles/bootstrap-icons-subset.scss`
 * and `src/styles/fonts/bootstrap-icons-subset.woff2`.
 *
 * The upstream webfont is 130,396 B and carries 2,050 glyphs; this app uses 39 of them, and the
 * icon stylesheet is a global style in angular.json, so that font is on the FIRST PAINT of every
 * visit. Subsetting it is the largest first-visit saving available without touching app code.
 *
 * Run it whenever a `bi-*` class is added or removed:
 *
 *   pip install fonttools brotli      # once; pyftsubset is not an npm package
 *   node scripts/build-bootstrap-icons-subset.mjs
 *
 * `--check` is the gate that makes forgetting that survivable. It needs no Python, so every
 * `npm run build*` lane runs it as a pre-hook: an icon added without regenerating fails the
 * build instead of rendering as a blank box in production. It cannot live in `ng test` — that
 * suite runs in a browser and has no filesystem.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';

const SRC_DIR = 'src';
const MAP = JSON.parse(readFileSync('node_modules/bootstrap-icons/font/bootstrap-icons.json', 'utf8'));
const FONT_IN = 'node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2';
const FONT_OUT = 'src/styles/fonts/bootstrap-icons-subset.woff2';
const SCSS_OUT = 'src/styles/bootstrap-icons-subset.scss';
const BACKSLASH = String.fromCharCode(92);

/** Every `bi-<name>` in the app source that is a real Bootstrap Icons name, sorted. */
function usedIconNames(dir = SRC_DIR) {
  const names = new Set();
  const walk = (d) => {
    for (const entry of readdirSync(d)) {
      const p = join(d, entry);
      if (statSync(p).isDirectory()) walk(p);
      else if (['.html', '.ts', '.scss'].includes(extname(p)))
        for (const m of readFileSync(p, 'utf8').matchAll(/\bbi-[a-z0-9-]+/g))
          if (m[0].slice(3) in MAP) names.add(m[0].slice(3));
    }
  };
  walk(dir);
  return [...names].sort();
}

/** [name, codepoint] for every rule the generated stylesheet declares. */
function definedRules() {
  const out = [];
  const lines = readFileSync(SCSS_OUT, 'utf8').split('\n');
  for (let i = 0; i < lines.length; i++) {
    const head = /^\.bi-([a-z0-9-]+)::before \{$/.exec(lines[i]);
    const body = head && /^ {2}content: "(.)([0-9a-f]+)";$/.exec(lines[i + 1] ?? '');
    if (body && body[1] === BACKSLASH) out.push([head[1], parseInt(body[2], 16)]);
  }
  return out;
}

const used = usedIconNames();

if (process.argv.includes('--check')) {
  // Name AND codepoint. A stylesheet that declares every used class can still point all of them
  // at the wrong glyph, which renders as raw text instead of an icon and which no unit test
  // asserts on: that shipped once while OBRS-392 was being written, and only a screenshot of the
  // built bundle caught it.
  const rules = definedRules();
  const defined = rules.map(([n]) => n);
  const missing = used.filter((n) => !defined.includes(n));
  const extra = defined.filter((n) => !used.includes(n));
  const wrong = rules.filter(([n, cp]) => cp !== MAP[n]).map(([n]) => n);
  if (missing.length || extra.length || wrong.length) {
    console.error(`${SCSS_OUT} is out of date with the icons ${SRC_DIR}/ uses.`);
    if (missing.length) console.error(`  used but NOT in the subset (would render blank): ${missing.join(', ')}`);
    if (extra.length) console.error(`  in the subset but no longer used: ${extra.join(', ')}`);
    if (wrong.length) console.error(`  codepoint does not match bootstrap-icons.json: ${wrong.join(', ')}`);
    console.error('  fix: pip install fonttools brotli && node scripts/build-bootstrap-icons-subset.mjs');
    process.exit(1);
  }
  console.log(`bootstrap-icons subset up to date (${used.length} icons)`);
  process.exit(0);
}

execFileSync(
  'pyftsubset',
  [
    FONT_IN,
    `--unicodes=${used.map((n) => 'U+' + MAP[n].toString(16).toUpperCase()).join(',')}`,
    '--flavor=woff2',
    '--layout-features=',
    '--no-hinting',
    `--output-file=${FONT_OUT}`,
  ],
  { stdio: 'inherit' }
);

const rules = used
  .map((n) => `.bi-${n}::before {\n  content: "${BACKSLASH}${MAP[n].toString(16)}";\n}`)
  .join('\n');

writeFileSync(
  SCSS_OUT,
  `// GENERATED by scripts/build-bootstrap-icons-subset.mjs — do not edit by hand.
//
// OBRS-392: replaces \`node_modules/bootstrap-icons/font/bootstrap-icons.css\` in angular.json.
// That file ships all 2,050 glyphs and all 2,050 \`content\` rules on first paint; this one
// carries the ${used.length} icons the app actually uses. The selectors are copied from upstream
// v1.11.3 verbatim so nothing about how an existing \`<i class="bi bi-x">\` renders changes —
// only the glyphs nobody references are gone.
@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("./fonts/bootstrap-icons-subset.woff2") format("woff2");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -0.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules}
`
);

console.log(`${used.length} icons -> ${FONT_OUT} + ${SCSS_OUT}`);
